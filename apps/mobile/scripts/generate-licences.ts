// Writes src/lib/licences.data.ts from package-lock.json (the licences screen).
// Run after any dependency change: npx tsx scripts/generate-licences.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { packageLicencesFromLock } from '../src/lib/licences';

const root = new URL('../', import.meta.url);
const list = packageLicencesFromLock(JSON.parse(readFileSync(new URL('package-lock.json', root), 'utf8')));
const body = list.map((p) => `  ${JSON.stringify(p)},`).join('\n');
writeFileSync(
  new URL('src/lib/licences.data.ts', root),
  `// Generated by scripts/generate-licences.ts from package-lock.json. Do not edit.\n` +
    `import type { PackageLicence } from './licences';\n\n` +
    `export const PACKAGE_LICENCES: PackageLicence[] = [\n${body}\n];\n`,
);
console.log(`${list.length} packages`);
