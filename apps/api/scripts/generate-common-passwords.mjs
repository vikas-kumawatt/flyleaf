// Regenerates src/identity/common-passwords.data.ts (D-04-2, audit 06).
//
//   node scripts/generate-common-passwords.mjs
//
// Source: SecLists, Passwords/Common-Credentials/xato-net-10-million-passwords-100000.txt
// (the "10-million-password-list-top-100000" list, renamed upstream), MIT licence,
// pinned to one commit and checked against its SHA-256 so a regeneration is
// reproducible and an upstream edit cannot slip in unnoticed.
//
// Kept: entries at least MIN_LENGTH characters long (shorter ones are refused
// by the length rule before the list is consulted), stored in the form
// isCommonPassword() compares: NFC, lowercased, separators removed.

import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const COMMIT = 'c205c36a445bff37f8e58a9ec829105cd4975c58';
const PATH = 'Passwords/Common-Credentials/xato-net-10-million-passwords-100000.txt';
const SHA256 = '1472aafa2561df5e3293aee252aee3ca660c12b399a283cf808bb01b39be388b';
const MIN_LENGTH = 10; // passwordSchema's minimum

export const normaliseForList = (p) => p.normalize('NFC').toLowerCase().replace(/[\s\-_.]/g, '');

const url = `https://raw.githubusercontent.com/danielmiessler/SecLists/${COMMIT}/${PATH}`;
const res = await fetch(url);
if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
const body = Buffer.from(await res.arrayBuffer());
const digest = createHash('sha256').update(body).digest('hex');
if (digest !== SHA256) throw new Error(`checksum mismatch: got ${digest}, want ${SHA256}`);

const lines = body.toString('utf8').split(/\r?\n/).filter(Boolean);
const kept = [...new Set(lines.filter((p) => p.length >= MIN_LENGTH).map(normaliseForList))].sort();
if (kept.some((p) => p.includes('\n') || p.includes('`') || p.includes('\\') || p.includes('${'))) {
  throw new Error('an entry needs escaping; extend the writer before regenerating');
}

const out = `// GENERATED by scripts/generate-common-passwords.mjs; do not edit by hand.
//
// Source: SecLists (https://github.com/danielmiessler/SecLists), MIT licence,
// Copyright (c) 2018 Daniel Miessler.
//   ${PATH}
//   commit ${COMMIT}, sha256 ${SHA256}
// ${lines.length} passwords in the source; ${kept.length} kept (at least ${MIN_LENGTH} characters),
// normalised NFC, lowercased, separators (space - _ .) removed.

export const SECLISTS_COMMON_PASSWORDS = \`${kept.join('\n')}\`;
`;

const target = fileURLToPath(new URL('../src/identity/common-passwords.data.ts', import.meta.url));
writeFileSync(target, out);
console.log(`wrote ${kept.length} entries to ${target}`);
