// Share cards (ST-07, ST-08; PRD §6.45, §6.37a, §17.5, §29.1 loop 1,
// §41.4, AC-18): who may fetch a card, what it may show, and the routes.
//
//   GET /v1/cards/finish/:id                 a finished read
//   GET /v1/cards/review/:id                 a review quote: its author only
//   GET /v1/cards/users/:id/stat/:stat       one statistic
//   GET /v1/cards/users/:id/profile          the profile
//   GET /v1/cards/users/:id/wall             the Wall collage, 4×4 or 3×5
//   GET /v1/cards/users/:id/year/:year/:card one Year in Review card (ST-09): the reader's own
//
// PRIVACY: a card follows the screen it shares.
//   - Who may fetch it: whoever may see that screen, through the same
//     canView() (a read, a review, an account). Anyone else gets the one
//     404 a random id gets ("Card not found."), byte for byte.
//   - A review quote is its author's alone to make (§41.4 "only the user's
//     own review, generated by that user"): anyone else's is that 404 too.
//     A review marked as having spoilers, or hidden by a moderator, shows
//     no text.
//   - Figures that add reads up (stat, profile, Wall) count PUBLIC reads only,
//     whoever asks, the owner included (§17.5: "the share card, being
//     public, uses public-visible figures"), and every such card says so.
//     A private or followers-only read never reaches one, so a card a
//     follower or the owner shares carries nothing a stranger may not see.
//   - A private account's profile, stat, Wall and Year in Review cards are
//     its owner's alone (owner decision on Phase 5 B): a follower who may
//     see the screen still gets the 404, so nothing of a private account
//     leaves the app as an image unless its owner sends it.
//   - A finish card is of one read: like GET /reads/:id, its owner may make
//     one of their own private read, and nobody else can fetch it.
//   - Explicit books (§7.8) are drawn without a cover and are left off the
//     profile and Wall cards, as on the public pages.
//
// NEVER FABRICATE (§17.4, ST-03): a statistic that has nothing to stand on is
// 422 `nothing_to_share`, not a zero or a guess; one based on part of the
// books says so, in the words of the stats screen.
//
// Responses are `image/png`, `Cache-Control: private` (who may see one
// depends on the viewer) with the content hash as ETag (304 on a match,
// after the authorization check), and `Server-Timing: render;dur=…`.

