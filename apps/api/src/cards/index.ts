const pngResponse = () => ({
  description: 'The card, 1080 × 1920 PNG.',
  content: { 'image/png': { schema: { type: 'string', format: 'binary' } } },
});
const cardErrors = () => ({ 404: errorResponseSchema, 422: errorResponseSchema, 429: errorResponseSchema });
const uuidParam = (name: string) => ({
  type: 'object',
  properties: { [name]: { type: 'string', format: 'uuid' } },
  required: [name],
}) as const;

async function send(req: FastifyRequest, reply: FastifyReply, card: Card) {
  const etag = `"${card.hash}"`;
  reply
    .header('cache-control', 'private, max-age=300')
    .header('etag', etag)
    .header('server-timing', `render;dur=${card.renderMs.toFixed(1)};desc="${card.cached ? 'cache' : 'render'}"`);
  if (req.headers['if-none-match'] === etag) return reply.code(304).send();
  return reply.type('image/png').header('content-disposition', 'inline; filename="flyleaf-card.png"').send(card.png);
}

