export const STAT_KINDS = ['books', 'pages', 'rating', 'author', 'genres', 'formats', 'streak'] as const;
export type StatKind = (typeof STAT_KINDS)[number];
export const WALL_LAYOUTS = ['4x4', '3x5'] as const;

/** Grapheme budgets per field: cut before layout, so a card's height never depends on its text. */
export const LIMITS = { title: 90, author: 60, name: 40, quote: 420, bio: 140, posterTitle: 60, posterAuthor: 40, bar: 40 } as const;

type CardKind = keyof typeof TEMPLATES;
type Model = FinishModel | ReviewModel | StatModel | ProfileModel | WallModel;

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const notFound = () => ApiError.notFound('Card not found.');
const nothing = (what: string) => ApiError.unprocessable('nothing_to_share', `There is nothing to put on this card yet: ${what}.`);

const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
/** 2026-10-12 → "12 Oct 2026". Fixed English, so a card does not change with the server's locale. */
export function cardDate(iso: string | null | undefined): string | null {
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(iso ?? '');
  return m ? `${Number(m[3])} ${MONTHS[Number(m[2]) - 1]} ${m[1]}` : null;
}

const plural = (n: number, one: string, many = `${one}s`) => (n === 1 ? one : many);
const num = (n: number) => n.toLocaleString('en-GB');

/** "AK" for "Aisha Khan": the first grapheme of the first two words. */
export function initials(name: string): string {
  return cleanText(name).split(' ').filter(Boolean).slice(0, 2).map((w) => graphemes(w)[0] ?? '').join('').toUpperCase() || '?';
}

/**
 * ST-03's sentence for a figure based on part of the books: "Based on 180
 * of 247 books — 67 have no page count." null when nothing is missing.
 */
export function coverageLine(c: { based_on: number; of: number }, missing: [one: string, many: string]): string | null {
  if (c.of === 0 || c.based_on >= c.of) return null;
  const left = c.of - c.based_on;
  return `Based on ${num(c.based_on)} of ${num(c.of)} ${plural(c.of, 'book')} — ${num(left)} ${left === 1 ? missing[0] : missing[1]}.`;
}

/** One statistic as a card, from public-only figures. Throws nothing_to_share where §17.4 forbids a figure. */
export function statModel(kind: StatKind, s: ReadingStats, handle: string): StatModel {
  const period = s.year === 'all' ? 'All time' : s.year;
  const base = { handle, period, caption: null, detail: null, bars: [] as StatBar[], coverage: null as string | null };
  switch (kind) {
    case 'books': {
      if (s.books_count === 0) throw nothing('no finished books');
      const undated = s.year !== 'all' && s.excluded.undated > 0
        ? `${num(s.excluded.undated)} undated ${plural(s.excluded.undated, 'book is', 'books are')} not counted in ${s.year}.`
        : null;
      return {
        ...base, heading: 'Books read', value: num(s.books_count), caption: plural(s.books_count, 'book'),
        detail: s.distinct_works_count < s.books_count ? `${num(s.distinct_works_count)} different ${plural(s.distinct_works_count, 'book')}` : null,
        coverage: undated,
      };
    }
    case 'pages':
      if (s.coverage.pages.based_on === 0) throw nothing('no finished book has a page count');
      return {
        ...base, heading: 'Pages read', value: num(s.pages_count), caption: plural(s.pages_count, 'page'),
        coverage: coverageLine(s.coverage.pages, ['has no page count', 'have no page count']),
      };
    case 'rating': {
      if (s.avg_rating === null) throw nothing('no rated books');
      const buckets = Object.entries(s.rating_distribution).sort((a, b) => Number(b[0]) - Number(a[0]));
      return {
        ...base, heading: 'Average rating', value: s.avg_rating.toFixed(1), caption: 'out of 5',
        bars: buckets.map(([k, v]) => ({ label: `${Number(k) % 1 === 0 ? Number(k).toFixed(0) : k} stars`, value: v, text: num(v) })),
        coverage: coverageLine(s.coverage.ratings, ['is unrated', 'are unrated']),
      };
    }
    case 'author': {
      const a = s.most_read_author;
      if (!a) throw nothing('no finished book has an author');
      return {
        ...base, heading: 'Most-read author', value: num(a.count), caption: clampText(a.name, LIMITS.name) || null,
        detail: plural(a.count, 'book'), coverage: coverageLine(s.coverage.authors, ['has no author recorded', 'have no author recorded']),
      };
    }
    case 'genres': {
      const top = s.genres.top.filter((g) => cleanText(g.name) !== '');
      if (top.length === 0) throw nothing('no finished book has a genre');
      return {
        ...base, heading: 'Top genre', value: num(top[0]!.count), caption: clampText(top[0]!.name, LIMITS.name),
        detail: plural(top[0]!.count, 'book'),
        bars: top.slice(0, 5).map((g) => ({ label: clampText(g.name, LIMITS.bar), value: g.count, text: num(g.count) })),
        coverage: coverageLine(s.coverage.genres, ['has no genre', 'have no genre']),
      };
    }
    case 'formats': {
      const f = s.format_breakdown;
      const known = [['print', 'in print', f.print], ['ebook', 'as ebooks', f.ebook], ['audiobook', 'as audiobooks', f.audiobook]] as const;
      const top = [...known].sort((a, b) => b[2] - a[2])[0]!;
      if (top[2] === 0) throw nothing('no finished book has a format recorded');
      return {
        ...base, heading: 'How I read', value: num(top[2]), caption: top[1],
        bars: known.map(([label, , v]) => ({ label: label === 'print' ? 'Print' : label === 'ebook' ? 'Ebook' : 'Audiobook', value: v, text: num(v) })),
        coverage: coverageLine(s.coverage.formats, ['has no format recorded', 'have no format recorded']),
      };
    }
    case 'streak': {
      // ST-06 framing: a live streak, or the longest; never a loss.
      const range = (r: { start: string; end: string } | null) => (r ? `${cardDate(r.start)} – ${cardDate(r.end)}` : null);
      if (s.current_streak > 0) {
        return {
          ...base, period: 'Reading streak', heading: 'Reading streak', value: num(s.current_streak), caption: plural(s.current_streak, 'day'),
          detail: s.longest_streak > s.current_streak ? `Longest: ${num(s.longest_streak)} days (${range(s.longest_streak_range)})` : null,
        };
      }
      if (s.longest_streak === 0) throw nothing('no reading logged');
      return {
        ...base, period: 'Reading streak', heading: 'Longest streak', value: num(s.longest_streak), caption: plural(s.longest_streak, 'day'),
        detail: range(s.longest_streak_range),
      };
    }
  }
}

type WorkRow = {
  title: string;
  author_name: string | null;
  cover_id: number | null;
  explicit: boolean;
};

/** The cover a reader sees for a read: their edition's, else the work's, else any edition's (as the Diary). */
const COVER_SQL = (edition: ReturnType<typeof sql>, work: ReturnType<typeof sql>) => sql`COALESCE(
  (SELECT e.ol_cover_id FROM editions e WHERE e.id = ${edition}), ${work}.ol_cover_id,
  (SELECT e2.ol_cover_id FROM editions e2 WHERE e2.work_id = ${work}.id AND e2.ol_cover_id IS NOT NULL
    ORDER BY e2.publish_year DESC NULLS LAST, e2.id LIMIT 1))`;
const AUTHOR_SQL = (work: ReturnType<typeof sql>) => sql`(SELECT a.name FROM work_authors wa JOIN authors a ON a.id = wa.author_id
  WHERE wa.work_id = ${work}.id ORDER BY wa.position, a.name LIMIT 1)`;

export interface CardServiceOptions {
  storage?: ObjectStorage | null;
  /** How covers missing from storage are fetched. Default: the shared outbound client. */
  fetchBytes?: FetchBytes;
  renderer?: CardRenderer;
  coverBudgetMs?: number;
}

export interface Card {
  png: Buffer;
  hash: string;
  cached: boolean;
  renderMs: number;
}

export class CardService {
  readonly renderer: CardRenderer;
  readonly images: CardImages;
  readonly #reading: ReadingService;
  readonly #reviews: ReviewService;

  constructor(private readonly db: Db, opts: CardServiceOptions = {}) {
    this.renderer = opts.renderer ?? new CardRenderer();
    this.images = new CardImages(opts.storage ?? null, opts.fetchBytes, opts.coverBudgetMs);
    this.#reading = new ReadingService(db);
    this.#reviews = new ReviewService(db);
  }

  async render(kind: CardKind, model: Model): Promise<Card> {
    return this.renderer.render(kind, model, () => (TEMPLATES[kind] as (m: Model) => ReturnType<typeof TEMPLATES.finish>)(model));
  }

  async #account(viewer: string | null, userId: string): Promise<{ handle: string; name: string; avatarKey: string | null; bio: string | null; favourites: string[] }> {
    if (!UUID_RE.test(userId)) throw notFound();
    const rel = await loadRelationship(this.db, viewer, userId);
    if (!canViewWith(viewer, userId, rel)) throw notFound();
    const [p] = await this.db.execute<{ username: string; display_name: string | null; avatar_key: string | null; bio: string | null; favourite_work_ids: string[] | string | null }>(sql`
      SELECT username, display_name, avatar_key, bio, favourite_work_ids FROM profiles WHERE user_id = ${userId}::uuid`);
    if (!p) throw notFound();
    const favs = Array.isArray(p.favourite_work_ids)
      ? p.favourite_work_ids.map(String)
      : String(p.favourite_work_ids ?? '').replace(/^\{|\}$/g, '').split(',').filter(Boolean);
    return {
      handle: p.username,
      name: clampText(orFallback(p.display_name, p.username), LIMITS.name),
      avatarKey: p.avatar_key,
      bio: p.bio,
      favourites: favs,
    };
  }

  async #work(workId: string, editionId: string | null): Promise<WorkRow> {
    const [w] = await this.db.execute<WorkRow>(sql`
      SELECT w.title, ${AUTHOR_SQL(sql`w`)} AS author_name,
             ${COVER_SQL(sql`${editionId}::uuid`, sql`w`)} AS cover_id,
             w.maturity = 'explicit' AS explicit
        FROM works w WHERE w.id = ${workId}::uuid`);
    if (!w) throw notFound();
    return w;
  }

  /** A finished read, for whoever may see the read (GET /reads/:id's rule). */
  async finish(viewer: string | null, readId: string): Promise<FinishModel> {
    if (!UUID_RE.test(readId)) throw notFound();
    const read = await this.#reading.get(viewer, readId);
    if (!read) throw notFound();
    if (read.status !== 'finished') {
      throw ApiError.unprocessable('card_unavailable', 'A finish card is for a finished book.');
    }
    const [w, account] = await Promise.all([this.#work(read.work_id, read.edition_id ?? null), this.#account(viewer, read.user_id)]);
    const [cover] = await this.images.covers([w.explicit ? null : w.cover_id]);
    return {
      handle: account.handle,
      title: clampText(orFallback(w.title, 'Untitled'), LIMITS.title),
      author: clampText(w.author_name, LIMITS.author) || null,
      cover: cover ?? null,
      rating: read.rating,
      hearted: read.hearted,
      finishedOn: cardDate(read.finished_at),
    };
  }

  /** A review quote: its author's own, only (§41.4). */
  async review(viewer: string | null, reviewId: string): Promise<ReviewModel> {
    if (!UUID_RE.test(reviewId) || viewer === null) throw notFound();
    let review;
    try {
      review = await this.#reviews.getReview(reviewId, viewer);
    } catch (err) {
      if (err instanceof ApiError && err.status === 404) throw notFound();
      throw err;
    }
    if (review.user_id !== viewer) throw notFound();
    const [row] = await this.db.execute<{ hidden: boolean; edition_id: string | null }>(sql`
      SELECT rv.hidden_at IS NOT NULL AS hidden, r.edition_id
        FROM reviews rv JOIN reads r ON r.id = rv.read_id WHERE rv.id = ${reviewId}::uuid`);
    if (!row) throw notFound();
    const [w, account] = await Promise.all([this.#work(review.work_id, row.edition_id), this.#account(viewer, viewer)]);
    const [cover] = await this.images.covers([w.explicit ? null : w.cover_id]);
    const quote = review.has_spoilers || row.hidden ? null : clampText(review.body, LIMITS.quote);
    return {
      handle: account.handle,
      name: account.name,
      title: clampText(orFallback(w.title, 'Untitled'), LIMITS.title),
      author: clampText(w.author_name, LIMITS.author) || null,
      cover: cover ?? null,
      rating: review.rating,
      quote: quote === '' ? null : quote,
    };
  }

  async stat(viewer: string | null, userId: string, kind: StatKind, year?: string, tz?: string): Promise<StatModel> {
    const account = await this.#account(viewer, userId);
    let stats: ReadingStats;
    try {
      stats = await this.#reading.getStats(viewer, userId, year, tz, { publicOnly: true });
    } catch (err) {
      if (err instanceof ApiError && err.status === 404) throw notFound();
      throw err;
    }
    return statModel(kind, stats, account.handle);
  }

  async profile(viewer: string | null, userId: string, tz?: string): Promise<ProfileModel> {
    const zone = checkZone(tz);
    const account = await this.#account(viewer, userId);
    const year = Number(localDate(zone).slice(0, 4));
    const [counts, favRows, avatar] = await Promise.all([
      this.db.execute<{ this_year: number; all_time: number }>(sql`
        SELECT count(*) FILTER (WHERE finished_at >= ${`${year}-01-01`}::date AND finished_at < ${`${year + 1}-01-01`}::date)::int AS this_year,
               count(*)::int AS all_time
          FROM reads WHERE user_id = ${userId}::uuid AND status = 'finished' AND visibility = 'public'`),
      account.favourites.length === 0
        ? Promise.resolve([] as Array<WorkRow & { id: string }>)
        : this.db.execute<WorkRow & { id: string }>(sql`
            SELECT w.id, w.title, ${AUTHOR_SQL(sql`w`)} AS author_name, ${COVER_SQL(sql`NULL::uuid`, sql`w`)} AS cover_id, false AS explicit
              FROM works w
             WHERE w.id IN (${sql.join(account.favourites.map((id) => sql`${id}::uuid`), sql`, `)})
               AND w.merged_into_id IS NULL AND w.maturity <> 'explicit'`),
      this.images.avatar(account.avatarKey),
    ]);
    const byId = new Map(favRows.map((r) => [String(r.id), r]));
    const favWorks = account.favourites.flatMap((id) => (byId.has(id) ? [byId.get(id)!] : [])).slice(0, 4);
    const covers = await this.images.covers(favWorks.map((w) => w.cover_id));
    return {
      handle: account.handle,
      name: account.name,
      initials: initials(account.name),
      avatar,
      bio: clampText(account.bio, LIMITS.bio) || null,
      favourites: favWorks.map((w, i) => poster(w, covers[i] ?? null)),
      year,
      booksThisYear: Number(counts[0]?.this_year ?? 0),
      booksAllTime: Number(counts[0]?.all_time ?? 0),
    };
  }

  async wall(viewer: string | null, userId: string, layout: WallLayout = '4x4', year?: string): Promise<WallModel> {
    if (year !== undefined && !/^\d{4}$/.test(year)) throw ApiError.unprocessable('invalid_year', 'Year is YYYY.', 'year');
    const account = await this.#account(viewer, userId);
    const { cols, rows } = WALL_GRID[layout];
    const slots = cols * rows;
    const range = year === undefined ? sql`` : sql`AND r.finished_at >= ${`${year}-01-01`}::date AND r.finished_at < ${`${Number(year) + 1}-01-01`}::date`;
    // Each book once (its latest finish), public reads only, newest first;
    // explicit and merged-away works left off, as on the public pages.
    const found = await this.db.execute<WorkRow & { total: number }>(sql`
      WITH latest AS (
        SELECT DISTINCT ON (r.work_id) r.work_id, r.edition_id, r.finished_at, r.updated_at
          FROM reads r
         WHERE r.user_id = ${userId}::uuid AND r.status = 'finished' AND r.visibility = 'public' ${range}
         ORDER BY r.work_id, r.finished_at DESC NULLS LAST, r.attempt_no DESC
      )
      SELECT w.title, ${AUTHOR_SQL(sql`w`)} AS author_name, ${COVER_SQL(sql`l.edition_id`, sql`w`)} AS cover_id,
             false AS explicit, count(*) OVER ()::int AS total
        FROM latest l JOIN works w ON w.id = l.work_id
       WHERE w.merged_into_id IS NULL AND w.maturity <> 'explicit'
       ORDER BY l.finished_at DESC NULLS LAST, l.updated_at DESC, w.id
       LIMIT ${slots}`);
    if (found.length === 0) throw nothing('no finished public books');
    const covers = await this.images.covers(found.map((w) => w.cover_id));
    return {
      handle: account.handle,
      name: account.name,
      layout,
      count: Number(found[0]!.total),
      posters: found.map((w, i) => poster(w, covers[i] ?? null)),
      year: year ?? null,
    };
  }
}

function poster(w: WorkRow, cover: Poster['cover']): Poster {
  return {
    title: clampText(orFallback(w.title, 'Untitled'), LIMITS.posterTitle),
    author: clampText(w.author_name, LIMITS.posterAuthor) || null,
    cover,
  };
}

function checkZone(tz: string | undefined): string {
  const zone = tz ?? 'UTC';
  if (!isTimeZone(zone)) throw ApiError.unprocessable('invalid_timezone', 'Unknown time zone. Send an IANA name such as Europe/London.', 'tz');
  return zone;
}

